package top.rootu.dddplayer.engine

/**
 * Упаковка стереопары в кадре.
 *
 * `MV_HEVC` и `SSIF` — не упаковка, а два отдельных потока (Apple Spatial Video и
 * 3D Blu-ray соответственно): для них движок отдаёт две текстуры вместо одной.
 */
enum class StereoLayout {
    MONO,

    /** Левый/правый кадр рядом по горизонтали. */
    SIDE_BY_SIDE,

    /** Левый/правый кадр друг над другом. */
    OVER_UNDER,

    /** MV-HEVC: базовый + дополнительный слой, два независимых кадра. */
    MV_HEVC,

    /** SSIF/MVC (3D Blu-ray): два элементарных потока. */
    SSIF
}

/** Геометрия проекции кадра на сцену. */
enum class Projection {
    /** Плоский экран. */
    FLAT,

    /** Плоский кадр на цилиндрическом экране (кривизна — пользовательская настройка). */
    CURVED,

    /** Равнопромежуточная 180°. */
    EQUIRECT_180,

    /** Равнопромежуточная 360°. */
    EQUIRECT_360,

    /** Fisheye (VR180-подобные съёмки). */
    FISHEYE,

    /** Кубическая развёртка. */
    CUBEMAP
}
