package top.rootu.dddplayer.engine

/**
 * Источник байт для нативного движка.
 *
 * Это точка, в которой сохраняются все серверные функции DDD. Движок не умеет
 * HTTP и не должен: сеть остаётся в Java, где она уже написана и работает —
 * TorrServer `/cache` с индикаторами загрузки, `LocalBridgeServer`,
 * `ParsingDataSource`, заголовки и cookies OkHttp, самоподписанные сертификаты.
 * Нативная часть получает только «дай байты с этой позиции».
 *
 * Реализация по умолчанию — [DataSourceEngineIo], поверх существующей цепочки
 * `androidx.media3.datasource.DataSource`. Интерфейс намеренно не знает про
 * media3: единый движок обязан оставаться свободным от него, иначе удаление
 * Media3-бекенда (шаг 13) невозможно.
 *
 * Контракт вызовов:
 *  - объект передаётся в движок **уже открытым**: [size] и [seekable]
 *    спрашиваются один раз, до первого [read];
 *  - [read] и [seekTo] вызываются из потока демукса (нативного), но никогда
 *    одновременно;
 *  - [close] вызывает движок, когда сессия закрыта. Java-сторона сама источник
 *    не закрывает: только движок знает, что он больше не читает.
 *
 * Имена методов и их подписи проверяются при `System.loadLibrary` через
 * `GetMethodID` в `jni_io_source.cpp` — переименование поля здесь ломает загрузку
 * сразу, а не на первом чтении.
 */
interface EngineIo {

    /**
     * Читает в [buffer] со смещения [offset] не больше [length] байт.
     *
     * Семантика `java.io.InputStream`, а не media3: `-1` — конец данных.
     * Возврат меньшего числа байт, чем запрошено, — норма.
     *
     * Возвращать 0 при живом источнике не следует: нативная сторона повторит
     * чтение несколько раз и затем сочтёт источник сломанным (ноль нельзя
     * отдать в AVIO — FFmpeg трактует любой не-положительный ответ как EOF и
     * закрывает поток окончательно).
     */
    fun read(buffer: ByteArray, offset: Int, length: Int): Int

    /**
     * Переходит на абсолютную позицию [position] от начала данных.
     *
     * Только абсолютные позиции: арифметику `SEEK_CUR`/`SEEK_END` делает
     * нативная сторона, которая и так ведёт учёт прочитанного.
     *
     * @return фактическая позиция или отрицательное число при ошибке.
     */
    fun seekTo(position: Long): Long

    /** Полный размер в байтах или `-1`, если неизвестен (live, chunked). */
    fun size(): Long

    /**
     * Можно ли перематывать.
     *
     * От этого зависит `AVIOContext.seekable`, а значит — сможет ли демуксер
     * дочитать `moov` в конце прогрессивного MP4. Соврать «да» для неперематываемого
     * источника хуже, чем сказать «нет»: вместо честного отказа получится ошибка
     * чтения посреди открытия.
     */
    fun seekable(): Boolean

    /** Имя для логов: URL или тип источника. */
    fun name(): String

    /** Освобождает источник. Вызывается движком ровно один раз. */
    fun close()
}
