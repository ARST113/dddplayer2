/*
 * tone_map.h — PQ/HLG → SDR-панель: параметры и эталон на CPU.
 *
 * Это шаг 6 (UNIFIED-ENGINE.md §6) и единственное место, где закрывается
 * исходная проблема проекта. Смысл в §2: на гарнитуре нет системного
 * HDR-конвейера — `HdrCapabilities` пуст, композитор в `ColorMode::NATIVE`,
 * `hdr metadata types=0`. PQ-сигнал, отданный такому композитору, трактуется как
 * обычный SDR, и получается знакомая вымытая тёмная картинка. Значит
 * HDR-метаданные нужны не для «включения HDR-режима» — его нет, — а как ВХОДНЫЕ
 * ДАННЫЕ тонмаппера.
 *
 * Насколько именно вымытая — считается, а не описывается словами. Пиковый белый
 * HDR10 (1000 нит) в PQ — это код 0.7518. Без тонмаппинга он уходит на панель как
 * есть и даёт 192 из 255, то есть светло-серый вместо белого; с тонмаппингом в
 * 500 нит — ровно 255. Отсюда и тест `peakWhiteReachesFullScale`.
 *
 * Кривая — BT.2390 EETF (Hermite-сплайн с коленом), а не Reinhard/Hable из
 * `pico-hdr-ffmpeg-lab/shaders/st2084_tonemap.glsl`. Причина: у лабораторного
 * шейдера тон-кривая сжимает ВСЁ, включая диапазон, который панель показывает
 * без потерь, а множитель `vec3(100.0, 93.0, 100.0) * 0.70` подобран на глаз и
 * тайно правит баланс белого (зелёный на 7 % ниже). EETF ниже колена — тождество:
 * контент до 100 нит проходит бит-в-бит, сжимается только то, что панель физически
 * не может показать. Это проверяемое свойство, а не вкус (`belowKneeIsIdentity`).
 *
 * Тонмаппинг применяется к яркости, а не к каналам по отдельности: все три
 * линейных канала умножаются на ОДНО отношение. Поканальная кривая тянет цветность
 * к серому тем сильнее, чем ярче пиксель, — закат теряет насыщенность именно там,
 * где она заметнее всего. Одинаковый множитель сохраняет цветность точно
 * (`toneMapPreservesChromaticity`).
 */
#pragma once

#include <cstdint>

namespace ddd {

/** Передаточная характеристика источника. Значения — как в `MediaFormat`. */
enum class ColorTransfer : int {
    /** Обычное SDR: тонмаппинг не нужен, путь шага 4 остаётся бит-в-бит. */
    kSdr = 0,
    /** ST 2084 / PQ — HDR10, HDR10+, DV профиль 8.1. */
    kPq = 1,
    /** ARIB STD-B67 / HLG. */
    kHlg = 2
};

/**
 * Параметры тонмаппинга. Из пробинга контейнера плюс свойства панели.
 *
 * Пер-файловые, а не пер-кадровые: mastering display и maxCLL описывают весь
 * поток. Пересчёт производных величин делает [ToneMapUniforms].
 */
struct HdrParams {
    ColorTransfer transfer = ColorTransfer::kSdr;

    /**
     * Пиковая яркость панели, кд/м². 500 — измеренное значение гарнитуры
     * (`mMaxLuminance=500.0` в `HdrCapabilities`, §2).
     */
    float display_peak_nits = 500.f;

    /**
     * Пиковая яркость мастеринга, кд/м². 0 — брать [max_cll_nits], а если и его
     * нет, то 1000 как типовое значение HDR10.
     *
     * Именно ради этого числа собирается `hdr-static-info`: тонмаппер обязан
     * знать, ОТКУДА сжимать. Ошибка здесь видна сразу — контент, смастеренный на
     * 1000 нит, при заявленных 4000 выйдет заметно темнее нужного.
     */
    float mastering_peak_nits = 0.f;

    /** maxCLL, кд/м²; 0 — нет данных. Резерв для [mastering_peak_nits]. */
    float max_cll_nits = 0.f;

    /**
     * maxFALL, кд/м²; 0 — нет данных.
     *
     * Пока не участвует в кривой и хранится осознанно: средняя яркость кадра
     * нужна динамическому (HDR10+/DV) тонмаппингу шагов 10+, а статическая
     * кривая обязана зависеть только от пика — иначе яркость всей сцены поехала
     * бы от содержимого соседних кадров.
     */
    float max_fall_nits = 0.f;

    /**
     * Регулятор яркости HDR, множитель к световому потоку ДО кривой.
     *
     * До кривой, а не после: умножение после тонмаппинга просто загонит верх в
     * клиппинг и съест детали в облаках. Множитель на входе означает «сделай
     * вид, что контент ярче» — тогда роль-офф пересчитается и детали сохранятся.
     * Аналог per-file `Set/GetHDRBrightness` из 4XVR.
     */
    float brightness = 1.f;

    /**
     * Гамма панели для обратного кодирования. 2.2 — sRGB-подобная панель Android
     * в `ColorMode::NATIVE`.
     *
     * Не 2.4 (BT.1886): 2.4 верна для студийного монитора в затемнённой комнате,
     * а здесь композитор цветом не управляет и трактует кадр как sRGB. Ошибка в
     * ту сторону даёт слишком контрастную, «проваленную в тенях» картинку.
     */
    float display_gamma = 2.2f;

    /**
     * Переводить BT.2020 → BT.709. Практически всегда true: HDR-контент в
     * BT.2020, а панель в NATIVE показывает примерно sRGB/BT.709, и без перевода
     * насыщенные цвета уезжают (небо и трава — самое заметное).
     */
    bool convert_gamut = true;

    /** Совместимый с 4XVR Hable-путь для DV; HDR10/HLG остаются стандартными. */
    bool match_four_xvr = false;

    /** Реально ли нужен HDR-путь в шейдере. */
    bool active() const { return transfer != ColorTransfer::kSdr; }

    /** Пик источника с учётом резервов: mastering → maxCLL → 1000. */
    float source_peak_nits() const;
};

/**
 * Всё, что шейдеру нужно посчитанным заранее.
 *
 * Считается на CPU один раз на файл: в шейдере это были бы `pow` и `log` на
 * каждый пиксель кадра, то есть на 4K — 8.3 млн раз за кадр ради значений,
 * которые не меняются.
 */
struct ToneMapUniforms {
    int transfer = 0;
    /** 0 — BT.2390/HLG, 1 — извлечённый из 4XVR DV HDR-модификатор. */
    int mode = 0;
    /** PQ-код пика источника (нижняя граница `Lb` принята нулевой). */
    float src_max_pq = 1.f;
    /** PQ-код пика панели. */
    float dst_max_pq = 1.f;
    /** Колено сплайна BT.2390: ниже него кривая — тождество. */
    float knee = 1.f;
    /** Нормировка светового потока на пик панели. */
    float display_scale = 1.f;
    /** Показатель OOTF для HLG минус единица (умножение вместо деления). */
    float hlg_gamma_minus_one = 0.f;
    float brightness = 1.f;
    /** Обратная гамма панели для кодирования на выходе. */
    float inv_gamma = 1.f / 2.2f;
    /** BT.2020 → BT.709, column-major для GLSL; единичная, если перевод выключен. */
    float gamut[9] = {1.f, 0.f, 0.f, 0.f, 1.f, 0.f, 0.f, 0.f, 1.f};
};

/** Пересчитывает параметры в форму для шейдера. */
ToneMapUniforms BuildToneMapUniforms(const HdrParams &p);

// ─────────────────────── эталон на CPU (для проверок) ───────────────────────
//
// Тот же расчёт в double. Нужен не как «вторая реализация той же формулы» —
// такое совпадение ничего не доказывает, — а чтобы отделить ошибку в математике
// от ошибки в GL: если CPU и GPU расходятся, дело в шейдере, драйвере или
// точности, а если совпадают и оба не сходятся с посчитанным по ITU-R вручную,
// дело в формуле. Проверки на числа ITU-R лежат в Kotlin отдельно.

/** ST 2084 EOTF: PQ-код → световой поток, 1.0 = 10000 кд/м². */
double PqEotf(double code);

/** ST 2084 OETF, обратная к [PqEotf]. */
double PqOetf(double luminance);

/** ARIB STD-B67 обратная OETF: HLG-код → яркость сцены [0,1]. */
double HlgInverseOetf(double code);

/** Системная гамма HLG для пика панели: 1.2 + 0.42·log10(peak/1000). */
double HlgSystemGamma(double display_peak_nits);

/** BT.2390 EETF в PQ-области. Ниже колена — тождество. */
double Bt2390Eetf(double pq_code, double src_max_pq, double dst_max_pq);

/**
 * Полный путь для одного пикселя: нелинейный RGB источника → SDR-код панели.
 *
 * @param rgb_in  три PQ- или HLG-кода в [0,1] (то, что даёт матрица YCbCr→RGB).
 * @param rgb_out три значения в [0,1] для панели, уже с гаммой.
 */
void ToneMapPixel(const HdrParams &p, const double rgb_in[3], double rgb_out[3]);

}  // namespace ddd
