/*
 * gl_util.h — сборка GL-программ и проверка ошибок.
 *
 * Вынесено отдельно, потому что шейдеров будет больше одного: тонмаппинг (шаг 6),
 * reshaping Dolby Vision (шаг 10) и проекции (шаг 11) — это свои программы, и
 * логика «собрать, проверить, вытащить лог компилятора» у них общая.
 *
 * Главное здесь — не терять лог компилятора. GL при ошибке компиляции просто
 * отдаёт нулевой объект, и без `glGetShaderInfoLog` в logcat остаётся «чёрный
 * экран» без единой строки о причине.
 */
#pragma once

namespace ddd {

/**
 * Компилирует и линкует программу.
 *
 * @param vertex_src/fragment_src исходники GLSL ES 3.0 (с `#version 300 es`).
 * @param tag имя для логов: при ошибке видно, какая именно программа не собралась.
 * @return id программы или 0.
 */
unsigned BuildGlProgram(const char *vertex_src, const char *fragment_src, const char *tag);

/**
 * Логирует накопленные ошибки GL и очищает их.
 *
 * GL — машина состояний с отложенной диагностикой: ошибка остаётся в очереди до
 * прочтения, и без такой проверки она всплывает в следующем, невиновном вызове.
 *
 * @return true, если ошибок не было.
 */
bool CheckGlError(const char *what);

}  // namespace ddd
